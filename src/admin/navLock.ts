/**
 * Замок вкладок админки и «Выйти» как счётчик. Ставят его несколько владельцев: видимая вкладка, пока пишет, и ушедший
 * с экрана экземпляр «Итогов», который ещё повторяет потерянную запись. Флаг дал бы последнему снять замок у первого;
 * счётчик снимает замок, только когда его сняли все.
 */
export function createNavLock(apply: (locked: boolean) => void): (locked: boolean) => void {
  let count = 0;
  return (locked) => {
    count = Math.max(0, count + (locked ? 1 : -1));
    apply(count > 0);
  };
}
